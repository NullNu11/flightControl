// ========== 软件I2C底层操作 ==========

// 直接操作寄存器加速GPIO（比HAL_GPIO_WritePin快10倍以上）
#define SCL_HIGH()   (OLED_SCL_PORT->BSRR = OLED_SCL_PIN)
#define SCL_LOW()    (OLED_SCL_PORT->BSRR = (uint32_t)OLED_SCL_PIN << 16)
#define SDA_HIGH()   (OLED_SDA_PORT->BSRR = OLED_SDA_PIN)
#define SDA_LOW()    (OLED_SDA_PORT->BSRR = (uint32_t)OLED_SDA_PIN << 16)

static void I2C_Delay(void)
{
    // 增加延时提高通信可靠性，防止中断干扰导致误码
    for (volatile uint8_t i = 0; i < 4; i++) { __NOP(); }
}

static void I2C_Start(void)
{
    SDA_HIGH();
    SCL_HIGH();
    I2C_Delay();
    SDA_LOW();
    I2C_Delay();
    SCL_LOW();
}

static void I2C_Stop(void)
{
    SDA_LOW();
    SCL_HIGH();
    I2C_Delay();
    SDA_HIGH();
    I2C_Delay();
}

static void I2C_SendByte(uint8_t byte)
{
    for (uint8_t i = 0; i < 8; i++)
    {
        if (byte & 0x80) SDA_HIGH(); else SDA_LOW();
        byte <<= 1;
        I2C_Delay();
        SCL_HIGH();
        I2C_Delay();
        SCL_LOW();
    }
    // ACK
    SDA_HIGH();
    I2C_Delay();
    SCL_HIGH();
    I2C_Delay();
    SCL_LOW();
}

/**
 * @brief GPIO初始化 (PC11=SCL, PC12=SDA)
 */
static void SSD1306_GPIO_Init(void)
{
    __HAL_RCC_GPIOC_CLK_ENABLE();

    // PC11: 开漏输出+上拉
    GPIOC->MODER &= ~(3U << (11 * 2));    // 清除模式
    GPIOC->MODER |=  (1U << (11 * 2));    // 通用输出
    GPIOC->OTYPER |= (1U << 11);          // 开漏输出
    GPIOC->PUPDR &= ~(3U << (11 * 2));    // 清除上拉
    GPIOC->PUPDR |=  (1U << (11 * 2));    // 上拉
    GPIOC->OSPEEDR |= (3U << (11 * 2));   // 高速
    GPIOC->BSRR = GPIO_PIN_11;            // SCL HIGH

    // PC12: 开漏输出+上拉
    GPIOC->MODER &= ~(3U << (12 * 2));
    GPIOC->MODER |=  (1U << (12 * 2));
    GPIOC->OTYPER |= (1U << 12);
    GPIOC->PUPDR &= ~(3U << (12 * 2));
    GPIOC->PUPDR |=  (1U << (12 * 2));
    GPIOC->OSPEEDR |= (3U << (12 * 2));
    GPIOC->BSRR = GPIO_PIN_12;            // SDA HIGH
}

